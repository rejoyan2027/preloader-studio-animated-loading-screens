/** Preloader Studio editable JavaScript source; see SOURCE-README.md. */
(function(){'use strict';
var root=document.getElementById('psx-admin');
if(!root)return;
var preview=root.querySelector('#psx-preview'),preset=root.querySelector('#psx-preset'),accent=root.querySelector('#psx-accent'),bg=root.querySelector('#psx-bg'),head=root.querySelector('#psx-headline'),sub=root.querySelector('#psx-subtitle'),stage=root.querySelector('#psx-admin-stage'),types=window.prelstan_auth_admin&&window.prelstan_auth_admin.presets||{};
root.querySelectorAll('[data-psx-preset]').forEach(function(button){button.addEventListener('click',function(){var p=button.dataset.psxPreset,data=types[p];
if(!data)return;
preset.value=p;
preview.className='psx-account psx-'+p;
accent.value=data[2];
bg.value=data[3];
preview.style.setProperty('--psx-panel',data[4]);
preview.style.setProperty('--psx-ink',data[5]);
preview.style.setProperty('--psx-accent',data[2]);
preview.style.setProperty('--psx-canvas',data[3]);
root.querySelectorAll('[data-psx-preset]').forEach(function(b){var on=b===button;
b.classList.toggle('selected',on);
b.setAttribute('aria-pressed',String(on));
});
});
});
accent.addEventListener('input',function(){preview.style.setProperty('--psx-accent',accent.value);
});
bg.addEventListener('input',function(){preview.style.setProperty('--psx-canvas',bg.value);
});
head.addEventListener('input',function(){root.querySelector('#psx-preview-headline').textContent=head.value||'Welcome back';
});
sub.addEventListener('input',function(){root.querySelector('#psx-preview-subtitle').textContent=sub.value||'Sign in to your experience';
});
root.querySelectorAll('[data-psx-device]').forEach(function(b){b.addEventListener('click',function(){stage.dataset.device=b.dataset.psxDevice;
root.querySelectorAll('[data-psx-device]').forEach(function(x){x.classList.toggle('selected',x===b);
});
});
});
root.querySelectorAll('[data-psx-view]').forEach(function(b){b.addEventListener('click',function(){var view=b.dataset.psxView;
root.querySelector('#psx-preview-title').textContent=view==='login'?'Sign in to your account':view==='register'?'Create your account':'Reset your password';
root.querySelector('#psx-preview-cta').textContent=view==='login'?'Sign in securely →':view==='register'?'Create account →':'Send reset link →';
root.querySelectorAll('.psx-preview-password').forEach(function(x){x.hidden=view!=='login';
});
stage.dataset.view=view;
if(typeof drawCustomPreview==='function')drawCustomPreview();
root.querySelectorAll('[data-psx-view]').forEach(function(x){x.classList.toggle('selected',x===b);
});
});
});
var id=root.querySelector('#psx-logo-id'),state=root.querySelector('#psx-logo-state');
root.querySelector('#psx-logo-pick').addEventListener('click',function(){if(!window.wp||!wp.media)return;
var frame=wp.media({title:'Select Brand Logo',library:{type:'image'},multiple:false});
frame.on('select',function(){var o=frame.state().get('selection').first().toJSON();
id.value=o.id;
state.textContent='Selected: '+(o.filename||'logo');
});
frame.open();
});
root.querySelector('#psx-logo-clear').addEventListener('click',function(){id.value=0;
state.textContent='Using site logo if available';
});

// Lightweight drag-order registration field editor. Only structured JSON reaches the server.
var fieldBox=root.querySelector('#psx-field-editor'),fieldData=root.querySelector('#psx-fields-data'),addField=root.querySelector('#psx-add-field');
if(fieldBox&&fieldData&&addField){
  var fields=Array.isArray(window.prelstan_auth_admin&&window.prelstan_auth_admin.fields)?window.prelstan_auth_admin.fields.map(function(f){return Object.assign({},f);
}):[];
  var typesAllowed=['text','email','tel','select','textarea','checkbox'];
  function element(tag,text,cls){var el=document.createElement(tag);
if(text!==undefined)el.textContent=text;
if(cls)el.className=cls;
return el;
}
  function editInput(label,key,field,i,tag){var outer=element('label',undefined,'psx-editor-control');
outer.appendChild(element('span',label));
var inp=element(tag||'input');
if(tag!=='textarea')inp.type='text';
inp.value=field[key]||'';
inp.addEventListener('input',function(){fields[i][key]=inp.value;
serialize();
});
outer.appendChild(inp);
return outer;
}
  var drawCustomPreview=function(){var target=root.querySelector('#psx-extra-preview');
if(!target)return;
target.replaceChildren();
var show=stage.dataset.view==='register';
target.hidden=!show;
if(!show)return;
    fields.forEach(function(f){var label=element('label',undefined,'psx-field');
label.appendChild(element('span',f.label||'New field'));
var el;
      if(f.type==='textarea')el=element('textarea');
else if(f.type==='select'){el=element('select');
(Array.isArray(f.options)?f.options:[]).forEach(function(opt){var o=element('option',opt);
el.appendChild(o);
});
}else{el=element('input');
el.type=f.type==='checkbox'?'checkbox':f.type;
}el.disabled=true;
el.placeholder=f.placeholder||'';
label.appendChild(el);
target.appendChild(label);
});
  };
  function serialize(){fieldData.value=JSON.stringify(fields);
addField.disabled=fields.length>=12;
drawCustomPreview();
}
  function paint(){fieldBox.replaceChildren();
fields.forEach(function(f,i){var card=element('section',undefined,'psx-field-row');
    var head=element('div',undefined,'psx-field-row-head');
head.appendChild(element('strong',(i+1)+'. '+(f.label||'New field')));
    [['↑',-1],['↓',1]].forEach(function(v){var btn=element('button',v[0]);
btn.type='button';
btn.className='button';
btn.disabled=(i+v[1]<0||i+v[1]>=fields.length);
btn.addEventListener('click',function(){var n=i+v[1],tmp=fields[n];
fields[n]=fields[i];
fields[i]=tmp;
paint();
});
head.appendChild(btn);
});
    var del=element('button','Remove');
del.type='button';
del.className='button';
del.addEventListener('click',function(){fields.splice(i,1);
paint();
});
head.appendChild(del);
card.appendChild(head);
    var grid=element('div',undefined,'psx-field-row-grid');
grid.appendChild(editInput('Field key', 'key',f,i));
grid.appendChild(editInput('Field label','label',f,i));
    var typeLabel=element('label',undefined,'psx-editor-control');
typeLabel.appendChild(element('span','Field type'));
var select=element('select');
typesAllowed.forEach(function(type){var o=element('option',type[0].toUpperCase()+type.slice(1));
o.value=type;
select.appendChild(o);
});
select.value=f.type||'text';
select.addEventListener('change',function(){f.type=select.value;
paint();
});
typeLabel.appendChild(select);
grid.appendChild(typeLabel);
    grid.appendChild(editInput('Placeholder / checkbox text','placeholder',f,i));
    var req=element('label',undefined,'psx-editor-required');
var cb=element('input');
cb.type='checkbox';
cb.checked=!!f.required;
cb.addEventListener('change',function(){f.required=cb.checked?1:0;
serialize();
});
req.appendChild(cb);
req.appendChild(element('span','Required field'));
grid.appendChild(req);
    if(f.type==='select'){var opts=editInput('Dropdown options (comma-separated)','options',Object.assign({},f,{options:Array.isArray(f.options)?f.options.join(', '):f.options}),i,'textarea');
var area=opts.querySelector('textarea');
area.addEventListener('input',function(){f.options=area.value.split(/[,\n]+/).map(function(x){return x.trim();
}).filter(Boolean);
serialize();
});
grid.appendChild(opts);
}
    card.appendChild(grid);
fieldBox.appendChild(card);
  });
serialize();
}
  addField.addEventListener('click',function(){if(fields.length>=12)return;
var key='custom_'+(fields.length+1);
while(fields.some(function(f){return f.key===key;
}))key+='a';
fields.push({key:key,label:'New field',type:'text',required:0,placeholder:'',options:[]});
paint();
});
  paint();
  // Serialize again just before form is submitted to preserve current order.
  var form=root.querySelector('#psx-design-editor');
if(form)form.addEventListener('submit',serialize);
}

})();
