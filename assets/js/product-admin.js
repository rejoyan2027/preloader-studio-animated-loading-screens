/** Preloader Studio editable JavaScript source; see SOURCE-README.md. */
(function(){'use strict';
 const form=document.getElementById('psp-editor');
if(!form)return;
 const gallery=document.getElementById('psp-gallery'),layoutInput=document.getElementById('psp-layout-id');
 const stage=document.getElementById('psp-preview-stage'),shell=document.getElementById('psp-preview-shell'),frame=document.getElementById('psp-preview-iframe'),status=document.getElementById('psp-preview-error');
 const devices={mobile:{w:390,h:844},tablet:{w:820,h:1180},desktop:{w:1440,h:900}};
let device='mobile',expanded=false,refreshId=null,observer=null;
 if(typeof prelstan_product_studio==='undefined')return;
 function read(){let d={};
new FormData(form).forEach((val,key)=>{const m=key.match(/^ps_products\[([^\]]+)\]$/);
if(m)d[m[1]]=val;
});
 ['show_rating','show_category','show_badge','show_button','enabled'].forEach(k=>{if(!d[k])d[k]='0';
});
 return d;
}
 function update(){const params=new URLSearchParams({action:'ps_studio_product_preview',nonce:prelstan_product_studio.nonce,device:device});
 const data=read();
Object.entries(data).forEach(([k,v])=>params.append(k,String(v)));
status.textContent='';
frame.src=prelstan_product_studio.previewUrl+'?'+params.toString();
}
 function fit(){const d=devices[device],p=stage.getBoundingClientRect();
const maxH=expanded?Math.max(500,window.innerHeight-250):Math.max(285,Math.min(540,window.innerHeight*.52));
const maxW=Math.max(190,p.width-22);
 const scale=Math.min(maxW/(d.w+14),maxH/(d.h+14),expanded?1:0.95);
shell.style.width=d.w+'px';
shell.style.height=d.h+'px';
shell.style.transform='scale('+scale+')';
shell.style.marginBottom=-(d.h*(1-scale))+'px';
shell.style.marginLeft='0';
shell.style.marginRight='0';
stage.style.minHeight=Math.ceil(d.h*scale+38)+'px';
document.getElementById('psp-preview-label').textContent=device[0].toUpperCase()+device.slice(1)+' · '+d.w+' × '+d.h+'px';
}
 function selectLayout(btn){if(!btn||!gallery.contains(btn))return;
layoutInput.value=btn.dataset.layout;
gallery.querySelectorAll('.psp-style-option').forEach(b=>{const chosen=b===btn;
b.classList.toggle('is-selected',chosen);
b.setAttribute('aria-pressed',String(chosen));
});
schedule();
}
 gallery.addEventListener('click',e=>selectLayout(e.target.closest('[data-layout]')));
 const filterBar=document.querySelector('.psp-gallery-filters');
 if(filterBar)filterBar.addEventListener('click',e=>{const btn=e.target.closest('[data-psp-filter]');
if(!btn)return;
const filter=btn.dataset.pspFilter;
filterBar.querySelectorAll('button').forEach(b=>{const active=b===btn;
b.classList.toggle('is-active',active);
b.setAttribute('aria-pressed',String(active));
});
let visible=0;
gallery.querySelectorAll('.psp-style-option').forEach(card=>{card.hidden=filter!=='all'&&card.dataset.group!==filter;
if(!card.hidden)visible++;
});
const count=document.getElementById('psp-gallery-counter');
if(count)count.textContent=visible+' / 32 designs';
});

 gallery.addEventListener('keydown',e=>{if(e.key==='Enter'||e.key===' '){const btn=e.target.closest('[data-layout]');
if(btn){e.preventDefault();
selectLayout(btn);
}}});
 function updateGallery(){const settings=read();
const parts=(settings.elements||'category,title,rating,price,button').split(',');
gallery.querySelectorAll('.psp-gallery-real').forEach(item=>{item.style.setProperty('--psp-accent',settings.accent||'#6754ed');
item.style.setProperty('--psp-ratio',settings.image_ratio||'4/5');
item.style.setProperty('--psp-radius',String(settings.rounded||18)+'px');
parts.forEach((part,i)=>item.style.setProperty('--psp-order-'+part,String(i+1)));
[['show_rating','is-no-rating'],['show_category','is-no-category'],['show_badge','is-no-badge'],['show_button','is-no-button']].forEach(([key,cls])=>item.classList.toggle(cls,settings[key]==='0'));
item.querySelectorAll('.ps-product-card').forEach(card=>{[...card.classList].filter(v=>v.startsWith('psp-hover-')).forEach(v=>card.classList.remove(v));
card.classList.add('psp-hover-'+(settings.hover||'classic'));
});
});
} 

 document.querySelectorAll('.psp-device-choices button').forEach(btn=>btn.addEventListener('click',()=>{device=btn.dataset.device;
document.querySelectorAll('.psp-device-choices button').forEach(b=>{b.classList.toggle('is-active',b===btn);
b.setAttribute('aria-pressed',String(b===btn));
});
fit();
update();
}));
 function schedule(){updateGallery();
clearTimeout(refreshId);
refreshId=setTimeout(update,240);
}
 form.addEventListener('input',function(e){if(e.target.matches('input[type=range]')){const out=e.target.parentNode.querySelector('output');
if(out)out.textContent=e.target.value+'px';
}schedule();
});
form.addEventListener('change',schedule);
 const expand=document.getElementById('psp-expand-preview');
expand.addEventListener('click',()=>{expanded=!expanded;
form.closest('.psp-workspace').classList.toggle('psp-expanded',expanded);
expand.textContent=expanded?'Close Expanded Preview':'Expand Preview';
fit();
});
 document.addEventListener('keydown',e=>{if(e.key==='Escape'&&expanded){expanded=false;
form.closest('.psp-workspace').classList.remove('psp-expanded');
expand.textContent='Expand Preview';
fit();
}});
 frame.addEventListener('load',()=>{try{if(frame.contentDocument&&frame.contentDocument.body&&frame.contentDocument.body.textContent.includes('Permission denied'))status.textContent='Preview needs a logged-in administrator session.';
}catch(e){}});
 if('ResizeObserver' in window){observer=new ResizeObserver(fit);
observer.observe(stage.parentNode);
}else window.addEventListener('resize',fit);
 // v2.1: Accessible reorder, per-category overrides and draft design management.
 const sorter=document.getElementById('psp-element-sort'),orderInput=document.getElementById('psp-elements-input');
 function syncOrder(){orderInput.value=[...sorter.children].map(el=>el.dataset.part).join(',');
schedule();
}
 sorter.addEventListener('click',e=>{const btn=e.target.closest('button'),li=e.target.closest('li');
if(!btn||!li)return;
 if(btn.classList.contains('psp-move-up')&&li.previousElementSibling)sorter.insertBefore(li,li.previousElementSibling);
 if(btn.classList.contains('psp-move-down')&&li.nextElementSibling)sorter.insertBefore(li.nextElementSibling,li);
 syncOrder();
});
 let dragged=null;
 sorter.addEventListener('dragstart',e=>{const row=e.target.closest('li');
if(!row)return;
dragged=row;
row.classList.add('is-dragging');
e.dataTransfer.effectAllowed='move';
});
 sorter.addEventListener('dragover',e=>{if(!dragged)return;
e.preventDefault();
const row=e.target.closest('li');
if(!row||row===dragged)return;
const midpoint=row.getBoundingClientRect().top+row.offsetHeight/2;
sorter.insertBefore(dragged,e.clientY<midpoint?row:row.nextSibling);
});
 sorter.addEventListener('dragend',()=>{if(dragged){dragged.classList.remove('is-dragging');
dragged=null;
syncOrder();
}});
 const ruleInput=document.getElementById('psp-category-rules'),ruleList=document.getElementById('psp-rule-list');
 const termSelect=document.getElementById('psp-rule-category'),ruleStyle=document.getElementById('psp-rule-layout');
 let rules={};
try{rules=JSON.parse(ruleInput.value)||{};
if(Array.isArray(rules))rules={};
}catch(e){rules={};
}
 function syncRules(){ruleInput.value=JSON.stringify(rules);
drawRules();
schedule();
}
 function drawRules(){ruleList.textContent='';
for(const [id,layout] of Object.entries(rules)){
 const option=termSelect.querySelector('option[value="'+CSS.escape(id)+'"]');
if(!option)continue;
 const row=document.createElement('div');
row.className='psp-rule-line';
const label=document.createElement('span');
label.textContent=option.textContent;
 const layoutLabel=document.createElement('strong');
layoutLabel.textContent=(gallery.querySelector('[data-layout="'+CSS.escape(layout)+'"] .psp-style-caption strong')?.textContent)||layout;
 const remove=document.createElement('button');
remove.type='button';
remove.className='button';
remove.textContent='Remove';
remove.addEventListener('click',()=>{delete rules[id];
syncRules();
});
 row.append(label,layoutLabel,remove);
ruleList.append(row);
 }if(!ruleList.children.length){const msg=document.createElement('p');
msg.className='description';
msg.textContent='No category rules yet — the default layout is used everywhere.';
ruleList.append(msg);
}}
 document.getElementById('psp-add-rule').addEventListener('click',()=>{const id=termSelect.value;
if(!id)return;
rules[id]=ruleStyle.value;
syncRules();
});
drawRules();
 const designsStatus=document.getElementById('psp-design-status'),designsList=document.getElementById('psp-saved-list');
 let designs=prelstan_product_studio.savedDesigns||{};
 async function designRequest(op,data){const payload=new URLSearchParams({action:'ps_studio_product_designs',nonce:prelstan_product_studio.designNonce,operation:op});
 for(const [k,v] of Object.entries(data||{})) if(k==='settings')Object.entries(v).forEach(([key,val])=>payload.append('settings['+key+']',val));
else payload.append(k,v);
 const res=await fetch(prelstan_product_studio.previewUrl,{method:'POST',credentials:'same-origin',headers:{'Content-Type':'application/x-www-form-urlencoded;charset=UTF-8'},body:payload});
 const output=await res.json();
if(!res.ok||!output.success)throw new Error(output.data?.message||'Unable to save design');
return output.data.designs;
}
 function loadDesign(config){const s=config.settings||{};
for(const [k,v] of Object.entries(s)){
 const field=form.elements.namedItem('ps_products['+k+']');
if(!field)continue;
 if(field.type==='checkbox')field.checked=String(v)==='1';
else field.value=v;
 }const l=gallery.querySelector('[data-layout="'+CSS.escape(s.layout||'atelier')+'"]');
if(l){gallery.querySelectorAll('[data-layout]').forEach(btn=>{btn.classList.toggle('is-selected',btn===l);
btn.setAttribute('aria-pressed',String(btn===l));
});
}
 const pieces=String(s.elements||'category,title,rating,price,button').split(',');
pieces.forEach(key=>{const li=sorter.querySelector('[data-part="'+CSS.escape(key)+'"]');
if(li)sorter.append(li);
});
 rules={};
try{rules=JSON.parse(s.category_rules||'{}')||{};
}catch(e){}drawRules();
 for(const range of form.querySelectorAll('input[type=range]')){const out=range.parentNode.querySelector('output');
if(out)out.textContent=range.value+'px';
}updateGallery();
schedule();
}
 function renderDesigns(){designsList.textContent='';
const entries=Object.entries(designs);
 if(!entries.length){const p=document.createElement('p');
p.className='description';
p.textContent='No saved designs yet.';
designsList.append(p);
return;
}
 for(const [id,design] of entries){const row=document.createElement('div');
row.className='psp-saved-line';
const title=document.createElement('strong');
title.textContent=design.name;
 const load=document.createElement('button');
load.type='button';
load.className='button button-secondary';
load.textContent='Load into editor';
load.addEventListener('click',()=>{loadDesign(design);
designsStatus.textContent='Loaded as draft. Click Save Product Layout to publish these changes.';
});
 const remove=document.createElement('button');
remove.type='button';
remove.className='button';
remove.textContent='Delete';
remove.addEventListener('click',async()=>{try{designs=await designRequest('delete',{id});
designsStatus.textContent='Draft design deleted.';
renderDesigns();
}catch(e){designsStatus.textContent=e.message;
}});
row.append(title,load,remove);
designsList.append(row);
}}
 document.getElementById('psp-save-design').addEventListener('click',async()=>{const name=document.getElementById('psp-design-name').value.trim();
if(!name){designsStatus.textContent='Enter a design name first.';
return;
}try{designsStatus.textContent='Saving draft…';
designs=await designRequest('save',{name,settings:read()});
document.getElementById('psp-design-name').value='';
designsStatus.textContent='Draft saved. Live shop unchanged.';
renderDesigns();
}catch(e){designsStatus.textContent=e.message;
}});
renderDesigns();

 const copyShortcode=document.getElementById('psp-copy-shortcode');
 if(copyShortcode) copyShortcode.addEventListener('click',async()=>{const field=document.getElementById('psp-shortcode');
if(!field)return;
 try{await navigator.clipboard.writeText(field.value);
copyShortcode.textContent='Copied!';
}
 catch(e){field.focus();
field.select();
copyShortcode.textContent='Select & copy';
}
 });
 updateGallery();
fit();
update();
})();
